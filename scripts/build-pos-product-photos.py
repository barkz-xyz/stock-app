"""Build small, metadata-free POS photos and their Vite import map (Pillow required)."""

from __future__ import annotations

import io
import json
import re
import unicodedata
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/assets/product-photos"
VARIANTS = ((192, 128, 6 * 1024), (384, 256, 16 * 1024))


def normalize(value: str) -> str:
    ascii_name = unicodedata.normalize("NFD", value)
    ascii_name = "".join(char for char in ascii_name if not unicodedata.combining(char))
    return re.sub(r"[^a-z0-9]+", " ", ascii_name.lower()).strip()


def encode(image: Image.Image, budget: int) -> tuple[bytes, int]:
    """Choose the highest quality within the byte cap; never silently exceed it."""
    best = None
    low, high = 32, 78
    while low <= high:
        quality = (low + high) // 2
        buffer = io.BytesIO()
        image.save(buffer, "WEBP", quality=quality, method=6)
        encoded = buffer.getvalue()
        if len(encoded) <= budget:
            best = (encoded, quality)
            low = quality + 1
        else:
            high = quality - 1
    if best is None:
        raise ValueError(f"Image cannot meet {budget}-byte budget at quality 32")
    return best


def main() -> None:
    manifest = json.loads((ROOT / "assets/pos-product-photos.json").read_text(encoding="utf-8"))
    catalog = json.loads((ROOT / "assets/productos-precios.json").read_text(encoding="utf-8"))
    catalog_names = {normalize(product["name"]) for product in catalog["products"]}
    aliases: dict[str, int] = {}
    imports, entries, report = [], [], []
    seen_ids = set()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for index, photo in enumerate(manifest["photos"]):
        photo_id = photo["id"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", photo_id) or photo_id in seen_ids:
            raise ValueError(f"Invalid or duplicate photo id: {photo_id}")
        seen_ids.add(photo_id)
        for name in photo["products"]:
            key = normalize(name)
            if key not in catalog_names or key in aliases:
                raise ValueError(f"Unknown or duplicate product: {name}")
            aliases[key] = index

        source = ROOT / photo["source"]
        with Image.open(source) as raw:
            image = ImageOps.exif_transpose(raw).convert("RGB")
            crop = photo.get("crop", [0, 0, 1, 1])
            left, top, right, bottom = crop
            if not (0 <= left < right <= 1 and 0 <= top < bottom <= 1):
                raise ValueError(f"Invalid crop: {photo_id}")
            width, height = image.size
            image = image.crop((round(left * width), round(top * height), round(right * width), round(bottom * height)))
            variants = []
            for width, height, budget in VARIANTS:
                thumbnail = ImageOps.fit(image, (width, height), Image.Resampling.LANCZOS)
                encoded, quality = encode(thumbnail, budget)
                filename = f"{photo_id}-{width}.webp"
                (OUTPUT / filename).write_bytes(encoded)
                imports.append(f"import photo{index}_{width} from './assets/product-photos/{filename}?no-inline'")
                variants.append({"file": filename, "width": width, "height": height, "bytes": len(encoded), "quality": quality, "budgetBytes": budget})
        entries.append(f"  {{ src: photo{index}_192, srcSet: `${{photo{index}_192}} 192w, ${{photo{index}_384}} 384w`, width: 192, height: 128 }}")
        report.append({"id": photo_id, "source": photo["source"], "sourceBytes": source.stat().st_size, "products": photo["products"], "variants": variants})

    alias_entries = [f"  [{json.dumps(key)}, photos[{index}]]" for key, index in aliases.items()]
    module = "// Generated by scripts/build-pos-product-photos.py. Edit assets/pos-product-photos.json instead.\n"
    module += "\n".join(imports) + "\n\nconst photos = [\n" + ",\n".join(entries) + "\n]\n\n"
    module += "const productPhotos = new Map([\n" + ",\n".join(alias_entries) + "\n])\n\n"
    module += "export function getProductPhoto(name = '') {\n  const key = name.normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()\n  return productPhotos.get(key)\n}\n"
    (ROOT / "src/productPhotos.js").write_text(module, encoding="utf-8")
    original_bytes = sum(item["sourceBytes"] for item in report)
    optimized_bytes = sum(variant["bytes"] for item in report for variant in item["variants"])
    result = {"photoCount": len(report), "matchedProducts": len(aliases), "catalogProducts": len(catalog_names), "sourceBytes": original_bytes, "webpBytesBothSizes": optimized_bytes, "photos": report}
    (ROOT / "assets/pos-product-photos-report.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Built {len(report)} photos for {len(aliases)}/{len(catalog_names)} products")
    print(f"Originals: {original_bytes:,} bytes; WebP (both sizes): {optimized_bytes:,} bytes; reduction: {100 * (1 - optimized_bytes / original_bytes):.1f}%")


if __name__ == "__main__":
    main()
