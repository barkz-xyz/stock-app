const key = () => crypto.randomUUID().replaceAll('-', '')

test('runtime provisioning requires separate migration credentials and explicit remote permission', async () => {
  await assert.rejects(provisionFromEnvironment({ DATABASE_URL: 'postgresql://unused@127.0.0.1/example' }), /MIGRATION_DATABASE_URL/)
  await assert.rejects(provisionFromEnvironment({ MIGRATION_DATABASE_URL: 'postgresql://unused@example.invalid/example', RUNTIME_DATABASE_ROLE: 'runtime_test' }), /PROVISION_ALLOW_REMOTE/)
  await assert.rejects(provisionFromEnvironment({ MIGRATION_DATABASE_URL: 'postgresql://unused@127.0.0.1/example', RUNTIME_DATABASE_ROLE: 'pg_unsafe' }), /RUNTIME_DATABASE_ROLE/)
})

test('a production app sells, refunds and receives changes using a limited PostgreSQL role', { skip: !process.env.TEST_DATABASE_URL, timeout: 60000 }, async t => {
  const schema = 'verify_role_' + key(), missingSchema = 'verify_missing_' + key()
  const runtimeRole = 'runtime_' + key(), ownerRole = 'owner_' + key(), elevatedRole = 'elevated_' + key(), memberRole = 'member_' + key()
  const unexpectedRole = 'unexpected_' + key()
  const password = crypto.randomBytes(48).toString('base64url')
  const connection = new URL(process.env.TEST_DATABASE_URL)
  assert.ok(['localhost', '127.0.0.1', '::1', '[::1]'].includes(connection.hostname), 'Role provisioning integration tests require an isolated local PostgreSQL fixture.')
  const admin = new pg.Client(postgresConfig(connection.href))
  const isolated = new URL(connection)
  isolated.searchParams.set('options', `-c search_path=${schema}`)
  const migrationPool = new pg.Pool(postgresConfig(isolated.href))
  let runtime, child, streams
  const generatedRoles = [unexpectedRole, runtimeRole, memberRole, elevatedRole, ownerRole]
  try {
    await admin.connect()
    await admin.query(`CREATE SCHEMA "${schema}"; CREATE SCHEMA "${missingSchema}"`)
    await migrateDatabase(migrationPool)
    const migration = await migrationPool.connect()
    try {
      await migration.query(`CREATE ROLE "${ownerRole}" NOLOGIN NOINHERIT; CREATE ROLE "${elevatedRole}" LOGIN SUPERUSER NOINHERIT;
        CREATE ROLE "${memberRole}" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
        GRANT "${ownerRole}" TO "${memberRole}";
        GRANT USAGE,CREATE ON SCHEMA "${schema}" TO "${ownerRole}";
        CREATE TABLE other_owner_table(id integer);
        ALTER TABLE other_owner_table OWNER TO "${ownerRole}"`)
      await assert.rejects(provisionRuntimeRole(migration, { role: elevatedRole, password }), /existing runtime role/)
      assert.equal((await migration.query('SELECT rolsuper FROM pg_roles WHERE rolname=$1', [elevatedRole])).rows[0].rolsuper, true)
      await assert.rejects(provisionRuntimeRole(migration, { role: memberRole, password }), /existing runtime role/)
      await assert.rejects(provisionRuntimeRole(migration, { role: runtimeRole, password: 'test' }), /strong random password/)
      const provisioned = await provisionRuntimeRole(migration, { role: runtimeRole, password })
      assert.equal(provisioned.created, true); assert.equal(provisioned.schema, schema)
      const before = (await migration.query('SELECT rolpassword FROM pg_authid WHERE rolname=$1', [runtimeRole])).rows[0].rolpassword
      const reused = await provisionRuntimeRole(migration, { role: runtimeRole, password: crypto.randomBytes(48).toString('base64url') })
      assert.equal(reused.created, false)
      assert.equal((await migration.query('SELECT rolpassword FROM pg_authid WHERE rolname=$1', [runtimeRole])).rows[0].rolpassword, before)
      await migration.query(`CREATE TABLE future_migration_table(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,value text);
        CREATE FUNCTION future_runtime_function() RETURNS integer LANGUAGE sql AS 'SELECT 42';
        SET ROLE "${ownerRole}"; CREATE TABLE future_other_owner_table(id integer); RESET ROLE`)
      await migration.query(`CREATE TABLE owned_runtime_fixture(id integer); ALTER TABLE owned_runtime_fixture OWNER TO "${runtimeRole}"`)
      await assert.rejects(provisionRuntimeRole(migration, { role: runtimeRole, password }), /ownership/)
      await migration.query('DROP TABLE owned_runtime_fixture')
      await grantRuntimePrivileges(migration, runtimeRole)
    } finally { migration.release() }

    const runtimeUrl = new URL(isolated)
    runtimeUrl.username = runtimeRole; runtimeUrl.password = password
    runtime = new pg.Client(postgresConfig(runtimeUrl.href)); await runtime.connect()
    await assertLimitedRuntimeRole(runtime)
    const privilege = (object, privilege) => runtime.query('SELECT has_table_privilege(current_user,$1,$2) AS allowed', [object, privilege])
    for (const table of ['items', 'sales', 'refunds', 'register_cash_entries', 'future_migration_table', 'future_other_owner_table']) {
      for (const operation of ['SELECT', 'INSERT', 'UPDATE', 'DELETE']) assert.equal((await privilege(table, operation)).rows[0].allowed, true)
      assert.equal((await privilege(table, 'TRUNCATE')).rows[0].allowed, false)
    }
    for (const operation of ['INSERT', 'UPDATE', 'DELETE', 'TRUNCATE']) assert.equal((await privilege('bakery_schema_migrations', operation)).rows[0].allowed, false)
    assert.equal((await privilege('bakery_schema_migrations', 'SELECT')).rows[0].allowed, true)
    await runtime.query("INSERT INTO future_migration_table(value) VALUES('limited runtime fixture')")
    assert.equal((await runtime.query('SELECT future_runtime_function() AS value')).rows[0].value, 42)
    for (const statement of ['CREATE TABLE forbidden_ddl(id integer)', 'ALTER TABLE items ADD COLUMN forbidden_column integer',
      'TRUNCATE sales', 'CREATE SCHEMA forbidden_schema', `CREATE ROLE "${unexpectedRole}"`, 'CREATE DATABASE forbidden_database']) {
      await assert.rejects(runtime.query(statement), { code: '42501' })
    }
    await t.test('an exact database name is mandatory before CLI provisioning changes privileges', async () => {
      await assert.rejects(provisionFromEnvironment({ MIGRATION_DATABASE_URL: isolated.href, RUNTIME_DATABASE_ROLE: runtimeRole,
        PROVISION_CONFIRM_DATABASE: 'wrong_database', PGSSLMODE: 'disable' }), /exact connected database/)
    })

    const childEnv = { ...deploymentTestEnvironment(process.env), NODE_ENV: 'production', DATABASE_AUTO_MIGRATE: 'false',
      DATABASE_URL: runtimeUrl.href, PGSSLMODE: 'disable', SESSION_SECRET: crypto.randomBytes(32).toString('hex'), PORT: '0' }
    const initializationProgram = "import {initializeStore,closeStore} from './server/store.js';try{await initializeStore()}finally{await closeStore()}"
    await admin.query(`GRANT USAGE ON SCHEMA "${missingSchema}" TO "${runtimeRole}"`)
    const missingUrl = new URL(runtimeUrl); missingUrl.searchParams.set('options', `-c search_path=${missingSchema}`)
    await assert.rejects(promisify(execFile)(process.execPath, ['--input-type=module', '-e', initializationProgram], {
      cwd: process.cwd(), env: { ...childEnv, DATABASE_URL: missingUrl.href }, timeout: 10000,
    }), error => /Database migrations are required/.test(error.stderr) && !error.stderr.includes(password))
    await admin.query(`DELETE FROM "${schema}".bakery_schema_migrations`)
    await assert.rejects(promisify(execFile)(process.execPath, ['--input-type=module', '-e', initializationProgram], {
      cwd: process.cwd(), env: childEnv, timeout: 10000,
    }), error => /Database migrations are required/.test(error.stderr))
    await admin.query(`INSERT INTO "${schema}".bakery_schema_migrations(version) VALUES($1)`, [databaseSchemaVersion])

    const userPassword = crypto.randomBytes(24).toString('base64url')
    await admin.query(`INSERT INTO "${schema}".app_users(id,username,name,role,password_hash,must_change_password)
      VALUES($1,'local_admin','Local role fixture','admin',$2,false)`, [crypto.randomUUID(), await hashPassword(userPassword)])
    let logs = ''
    child = spawn(process.execPath, ['server/index.js'], { cwd: process.cwd(), env: childEnv, stdio: ['ignore', 'pipe', 'pipe'] })
    child.stdout.on('data', value => { logs += value }); child.stderr.on('data', value => { logs += value })
    const port = await new Promise((resolve, reject) => {
      const timeout = setTimeout(() => reject(new Error('Local production-mode app startup timed out.')), 10000)
      child.once('exit', () => { clearTimeout(timeout); reject(new Error('Local production-mode app failed: ' + logs)) })
      child.stdout.on('data', () => { const match = /listening on port (\d+)/.exec(logs); if (match) { clearTimeout(timeout); resolve(match[1]) } })
    })
    const base = `http://127.0.0.1:${port}`
    let cookie
    const request = async (route, method = 'GET', body) => {
      const response = await fetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}), 'Idempotency-Key': crypto.randomUUID() },
        body: body === undefined ? undefined : JSON.stringify(body) })
      if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0]
      const data = await response.json()
      assert.ok(response.ok, JSON.stringify({ route, status: response.status, data }))
      return data
    }
    await request('/api/auth/login', 'POST', { username: 'local_admin', password: userPassword })
    await request('/api/register-sessions', 'POST', { openingCash: 0 })
    const item = await request('/api/items', 'POST', { name: 'Limited role bread', category: 'Bread', unit: 'pieces', quantity: 2, price: 1000, sellable: true, lowStockThreshold: 0 })
    const sale = await request('/api/sales/cash', 'POST', { items: [{ itemId: item.id, quantity: 1 }], cashReceived: 1000 })
    const refunded = await request(`/api/sales/${sale.id}/refunds`, 'POST', { amount: 500, items: [], restock: false })
    assert.equal(refunded.refundedTotal, 500)
    assert.equal((await request('/api/register-cash')).balance, 500)

    streams = new AbortController()
    const stream = await fetch(base + '/api/events', { headers: { Cookie: cookie }, signal: streams.signal })
    assert.equal(stream.status, 200)
    const reader = stream.body.getReader(), decoder = new TextDecoder()
    assert.match(decoder.decode((await reader.read()).value), /event: ready/)
    await admin.query("SELECT pg_notify('bakery_changes','local-runtime-fixture')")
    let timer
    try {
      const notification = await Promise.race([reader.read(), new Promise((_, reject) => { timer = setTimeout(() => reject(new Error('Limited-role app did not receive PostgreSQL LISTEN notification.')), 4000) })])
      assert.match(decoder.decode(notification.value), /event: change/)
    } finally { clearTimeout(timer); streams.abort(); streams = null; await reader.cancel().catch(() => {}) }
    assert.doesNotMatch(logs, /permission denied|change listener disconnected/i)
    assert.ok(!logs.includes(password))
  } finally {
    streams?.abort()
    if (child && child.exitCode === null) { child.kill(); await once(child, 'exit') }
    await runtime?.end(); await migrationPool.end()
    try {
      await admin.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE; DROP SCHEMA IF EXISTS "${missingSchema}" CASCADE`)
      for (const role of generatedRoles) {
        if ((await admin.query('SELECT 1 FROM pg_roles WHERE rolname=$1', [role])).rowCount) {
          await admin.query(`DROP OWNED BY "${role}" CASCADE; DROP ROLE "${role}"`)
        }
      }
    } finally { await admin.end() }
  }
})
